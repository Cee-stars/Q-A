export const DEFAULT_GENERATION_PROMPT = `あなたは英語スピーキング練習の出題者です。
学習者のレベル: {{level}}
話せるようになりたい場面: {{goal}}
扱いたいテーマ: {{themes}}

明日ぶんの質問を10問つくってください。

制約:
- **各問に日本語訳を必ず付ける**。意味が分からない質問には答えようがない
  - 訳は自然な話し言葉の日本語にする。直訳にしない
- **各問に手本の答えを必ず付ける**。これが無いと、言えない学習者は沈黙で終わる
  - 2〜3文。平易な構文だけを使い、学習者がその場で真似して言える高さにする
  - 難しい語や関係詞・完了形は避ける。ただし不自然な英語にはしない
- 1問15語以内。音読6秒に収まる長さ
- 抽象論ではなく、学習者自身の経験を語らせる質問にする
- 難易度の配分は easy 6問 / mid 3問 / hard 1問
  - easy: 考えずに即答できる。事実を答えるだけ
  - mid: 少し組み立てが要る。経験を説明させる
  - hard: 抽象的で、構成を考える必要がある
- 各問は45秒間ひとりで話し続けられる中身があること
- 次の質問と意味が重ならないこと:
{{exclude}}`

export const DEFAULT_CORRECTION_PROMPT = `あなたは英語スピーキングの添削者です。
学習者がこの質問に口頭で答えました。

質問: {{question}}
学習者の答え: {{answer}}

答えを、話し言葉として自然な英語に直してください。

制約:
- 直した文は2〜4文。それ以上は書かない
- 元の内容は変えない。学習者が言おうとしたことをそのまま自然にする
- 難しい語に置き換えない。学習者が実際に使える語彙にとどめる
- 直した箇所は最大3つまで。各理由は10語以内
- 説教・励まし・前置き・後置きは一切書かない`

export interface PromptVars {
  [key: string]: string
}

export function render(template: string, vars: PromptVars): string {
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) =>
    key in vars ? vars[key] : match,
  )
}
